-- Stage Tabs suggestion tickets.
-- Run once in your Supabase project: SQL Editor → New query → paste → Run.
-- The app can only add tickets, through submit_feedback(). Reading and
-- changing them is done from the Supabase dashboard (Table Editor → feedback).

create table if not exists public.feedback (
  id uuid primary key default gen_random_uuid(),
  ticket_number bigint generated by default as identity unique,
  created_at timestamptz not null default now(),
  status text not null default 'new' check (status in ('new', 'in progress', 'done', 'won''t fix')),
  kind text not null check (kind in ('idea', 'problem', 'song')),
  message text not null default '',
  from_name text,
  song_title text,
  song_artist text,
  song_body text,
  song_source text,
  app_version text,
  device text,
  notes text
);

-- No policies: the app's public key cannot read, change or delete rows.
alter table public.feedback enable row level security;

create or replace function public.submit_feedback(
  p_kind text,
  p_message text default '',
  p_from_name text default '',
  p_song_title text default '',
  p_song_artist text default '',
  p_song_body text default '',
  p_song_source text default '',
  p_app_version text default '',
  p_device text default ''
) returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  n bigint;
begin
  if p_kind not in ('idea', 'problem', 'song') then
    raise exception 'Unknown suggestion type';
  end if;
  -- Simple flood guard.
  if (select count(*) from feedback where created_at > now() - interval '1 minute') >= 20 then
    raise exception 'Too many suggestions right now. Try again in a minute.';
  end if;
  insert into feedback (kind, message, from_name, song_title, song_artist, song_body, song_source, app_version, device)
  values (
    p_kind,
    left(coalesce(p_message, ''), 5000),
    nullif(left(coalesce(p_from_name, ''), 100), ''),
    nullif(left(coalesce(p_song_title, ''), 300), ''),
    nullif(left(coalesce(p_song_artist, ''), 300), ''),
    nullif(left(coalesce(p_song_body, ''), 50000), ''),
    nullif(left(coalesce(p_song_source, ''), 50000), ''),
    left(coalesce(p_app_version, ''), 20),
    left(coalesce(p_device, ''), 40)
  )
  returning ticket_number into n;
  return n;
end;
$$;

revoke all on function public.submit_feedback(text, text, text, text, text, text, text, text, text) from public;
grant execute on function public.submit_feedback(text, text, text, text, text, text, text, text, text) to anon, authenticated;
